// Build TOC + pages
const tocEl = document.getElementById("toc");
const pagesEl = document.getElementById("pages");
const progEl = document.getElementById("prog");

function el(tag, attrs={}, html=""){
  const n = document.createElement(tag);
  Object.entries(attrs).forEach(([k,v]) => n.setAttribute(k,v));
  if (html) n.innerHTML = html;
  return n;
}

function render(){
  // TOC
  pages.forEach((p, i) => {
    const btn = el("button", {"data-i": i, "type": "button"});
    btn.innerHTML = `
<span class="num">${String(i+1).padStart(2,"0")}</span>
<span class="title">${p.title}<span class="meta">${p.subtitle}</span></span>
`;
    btn.addEventListener("click", () => go(i));
    tocEl.appendChild(btn);
  });

  // Pages
  pages.forEach((p, i) => {
    const page = el("article", {"class":"page", "data-i": i});
    page.innerHTML = `
<header>
<h2>${p.title}</h2>
<p class="sub">${p.subtitle}</p>
</header>

<div class="content">${p.content}</div>

<footer class="footer">
<div class="small">${p.footerNote || ""}</div>
<div class="navbtns">
<button class="btn" type="button" data-prev>← Prev</button>
<button class="btn primary" type="button" data-next>Next →</button>
</div>
</footer>
`;
    page.querySelector("[data-prev]").addEventListener("click", prev);
    page.querySelector("[data-next]").addEventListener("click", next);
    pagesEl.appendChild(page);
  });

  // Keyboard nav
  window.addEventListener("keydown", (e) => {
    if (e.key === "ArrowLeft") prev();
    if (e.key === "ArrowRight") next();
  });

  // Deep link
  const hash = location.hash.replace("#chapter-", "");
  const idx = hash ? Math.max(0, Math.min(pages.length-1, parseInt(hash,10)-1)) : 0;
  go(Number.isFinite(idx) ? idx : 0, true);
}

let current = 0;

function go(i, silent=false){
  current = i;

  // Activate page
  document.querySelectorAll(".page").forEach(p => p.classList.remove("active"));
  const page = document.querySelector(`.page[data-i="${i}"]`);
  if (page) page.classList.add("active");

  // Activate toc
  document.querySelectorAll("#toc button").forEach(b => b.classList.remove("active"));
  const btn = document.querySelector(`#toc button[data-i="${i}"]`);
  if (btn) btn.classList.add("active");

  // Progress
  const pct = ((i+1)/pages.length)*100;
  progEl.style.width = pct.toFixed(2) + "%";

  // Hash for sharing
  if (!silent) location.hash = `chapter-${i+1}`;
}

function prev(){ if (current > 0) go(current-1); }
function next(){ if (current < pages.length-1) go(current+1); }

// Copy chapter link
document.getElementById("copyLinkBtn").addEventListener("click", async () => {
  const url = location.href.split("#")[0] + `#chapter-${current+1}`;
  try{
    await navigator.clipboard.writeText(url);
    flash("Copied chapter link ✅");
  }catch(e){
    prompt("Copy this link:", url);
  }
});

function flash(msg){
  const n = document.createElement("div");
  n.textContent = msg;
  n.style.position="fixed";
  n.style.left="50%";
  n.style.top="18px";
  n.style.transform="translateX(-50%)";
  n.style.padding="10px 14px";
  n.style.borderRadius="999px";
  n.style.background="rgba(0,0,0,.55)";
  n.style.border="1px solid rgba(255,255,255,.16)";
  n.style.color="rgba(255,255,255,.92)";
  n.style.backdropFilter="blur(10px)";
  n.style.zIndex="9999";
  document.body.appendChild(n);
  setTimeout(()=>{ n.style.opacity="0"; n.style.transition="opacity .25s ease"; }, 1200);
  setTimeout(()=>{ n.remove(); }, 1600);
}

render();